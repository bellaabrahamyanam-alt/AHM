#!/usr/bin/env node
// Code graph for agents (proposal 011, task 015): where things are and who uses them. Usage:
//   node tools/make-graph.js            write graph/INDEX.md and graph/<domain>.md for every domain in tools/domains.json
//   node tools/make-graph.js --check    exit 1 if graph/ is out of date or over its size limits (run by tests/js/graph.test.js)
// Plain text and regular expressions, no parser, no dependencies. The same tree always gives the same text (sorted, no dates).
const fs = require('fs');
const path = require('path');
const cd = require('./check-domain');
const ROOT = path.join(__dirname, '..');
const GRAPH = path.join(ROOT, 'graph');
const LIMITS = { index: 6 * 1024, domain: 8 * 1024, longFile: 600 };
const CAP = { defines: 6, calls: 8, events: 6, users: 4, names: 8 };
const TOP_SKIP = new Set(['.git', 'graph', 'tests', 'tools', 'diffs', 'context']);
const WORDS = ['sidebar', 'map', 'layer', 'search', 'date', 'state', 'campaign', 'type', 'shape', 'route', 'note', 'place', 'overlay', 'language', 'icon', 'save'];
const IDENT = '[A-Za-z_$][\\w$]*';

const lineCount = (t) => (t === '' ? 0 : t.split('\n').length - (t.endsWith('\n') ? 1 : 0));
const capped = (list, n) => (list.length > n ? list.slice(0, n).join(', ') + ` +${list.length - n}` : list.join(', '));
const add = (map, key, value) => (map.has(key) ? map.get(key).push(value) : map.set(key, [value]));

/** What one file defines, calls, emits and listens to. */
function parse(file, text) {
  const php = file.endsWith('.php');
  const n = { path: file, php, browser: !php && file.startsWith('app/'), lines: lineCount(text), defines: new Set(), names: new Set(), calls: new Set(), emits: new Set(), listens: new Set(), tokens: new Set(text.match(new RegExp(IDENT, 'g')) || []) };
  const def = (name) => (n.defines.add(name), n.names.add(name));
  if (php) {
    for (const m of text.matchAll(/^\s*(?:abstract\s+|final\s+)?class\s+(\w+)/gm)) def(m[1]);
    for (const m of text.matchAll(/^\s*public\s+(?:static\s+)?function\s+(\w+)/gm)) n.defines.add(m[1]);
    return n;
  }
  for (const m of text.matchAll(new RegExp(`^(?:async\\s+)?function\\s*\\*?\\s*(${IDENT})`, 'gm'))) def(m[1]);
  for (const m of text.matchAll(new RegExp(`^(?:const|let|var|class)\\s+(${IDENT})`, 'gm'))) def(m[1]);
  for (const m of text.matchAll(/^(?:const|let|var)\s*\{([^}]*)\}\s*=/gm)) {
    for (const part of m[1].split(',')) {
      const name = part.split(':').pop().split('=')[0].trim();
      if (new RegExp(`^${IDENT}$`).test(name)) def(name);
    }
  }
  for (const m of text.matchAll(new RegExp(`^window\\.(${IDENT})\\s*=[^=]`, 'gm'))) def(m[1]);
  for (const m of text.matchAll(new RegExp(`\\bAHM\\.(${IDENT})(?:\\.(${IDENT}))?(\\s*=[^=])?`, 'g'))) {
    const name = m[2] ? `${m[1]}.${m[2]}` : m[1];
    if (name === 'on' || name === 'emit') continue;
    if (m[3]) n.defines.add('AHM.' + name);
    else n.calls.add(name);
  }
  for (const m of text.matchAll(/\bAHM\.emit\(\s*['"`]([^'"`]+)['"`]/g)) n.emits.add(m[1]);
  for (const m of text.matchAll(/\bAHM\.on\(\s*['"`]([^'"`]+)['"`]/g)) n.listens.add(m[1]);
  return n;
}

/** The graph as { files: { 'graph/<name>.md': text }, problems: [text] }. files: { path: text }; ownerOf(path) gives the domain. */
function build(files, ownerOf, opts = {}) {
  const lim = { ...LIMITS, ...(opts.limits || {}) };
  const domains = opts.domains || cd.DOMAINS;
  const nodes = Object.keys(files)
    .filter((p) => /\.(js|php)$/.test(p))
    .sort()
    .map((p) => Object.assign(parse(p, files[p]), { domain: ownerOf(p) }))
    .filter((n) => domains.includes(n.domain));

  const names = new Map(); // top-level name -> files that define it (names of 3 letters or fewer are too generic to follow)
  const browserDefs = new Map(); // the browser scripts share ONE global scope, so a doubled name is a real clash
  for (const n of nodes) {
    for (const name of n.names) {
      if (name.length > 3) add(names, name, n);
      if (n.browser) add(browserDefs, name, n.path);
    }
  }
  const users = new Map(nodes.map((n) => [n.path, new Set()]));
  const pairs = new Map(); // 'sidebar -> core' -> Set(names): a name of one domain used in another, not through AHM.*
  for (const [name, defs] of names) {
    if (defs.length !== 1) continue;
    const a = defs[0];
    for (const b of nodes) {
      if (b === a || b.php !== a.php || !b.tokens.has(name)) continue;
      users.get(a.path).add(b);
      if (a.domain !== b.domain && a.domain !== 'shared' && b.domain !== 'shared') {
        const key = `${b.domain} -> ${a.domain}`;
        if (!pairs.has(key)) pairs.set(key, new Set());
        pairs.get(key).add(name);
      }
    }
  }

  const out = {};
  const problems = [];
  const head = (title) => [`# ${title}`, '', '_Generated by `node tools/make-graph.js` from the source files and `tools/domains.json`. Do not edit by hand._', ''];

  for (const d of domains) {
    const mine = nodes.filter((n) => n.domain === d);
    const row = (n) => {
      const parts = [`- \`${n.path}\` ${n.lines} lines`];
      const defs = [...n.defines].sort();
      if (defs.length) parts.push('defines: ' + capped(defs, CAP.defines));
      if (n.calls.size) parts.push('AHM calls: ' + capped([...n.calls].sort(), CAP.calls));
      if (n.emits.size) parts.push('emits: ' + capped([...n.emits].sort(), CAP.events));
      if (n.listens.size) parts.push('listens: ' + capped([...n.listens].sort(), CAP.events));
      const who = [...users.get(n.path)].map((u) => `${u.domain}:${u.path}`).sort();
      if (who.length) parts.push('used by: ' + capped(who, CAP.users));
      return parts.join('. ');
    };
    const rows = mine.map(row);
    const text = [...head(`Graph: ${d} domain`), ...(rows.length ? rows : ['(no JavaScript or PHP files)']), ''].join('\n');
    out[`graph/${d}.md`] = text;
    const size = Buffer.byteLength(text);
    if (size > lim.domain) {
      const big = rows.map((r, i) => [Buffer.byteLength(r), mine[i].path]).sort((x, y) => y[0] - x[0] || (x[1] < y[1] ? -1 : 1)).slice(0, 3);
      problems.push(`graph/${d}.md is ${size} bytes, limit ${lim.domain}: split or shorten the largest entries (${big.map(([b, p]) => `${p} ${b}`).join(', ')})`);
    }
  }

  const table = ['| domain | files | lines | largest file |', '|---|---|---|---|'];
  for (const d of domains) {
    const mine = nodes.filter((n) => n.domain === d);
    const big = mine.reduce((m, n) => (!m || n.lines > m.lines ? n : m), null);
    table.push(`| ${d} | ${mine.length} | ${mine.reduce((s, n) => s + n.lines, 0)} | ${big ? `\`${big.path}\` (${big.lines})` : '-'} |`);
  }
  const longFiles = nodes.filter((n) => n.lines > lim.longFile).map((n) => `- \`${n.path}\` has ${n.lines} lines (limit ${lim.longFile}); owner: ${n.domain}`);
  const dups = [...browserDefs].filter(([, l]) => l.length > 1).sort((x, y) => (x[0] < y[0] ? -1 : 1)).map(([name, l]) => `- \`${name}\` is defined in ${l.join(', ')}`);
  const cross = [...pairs].sort((x, y) => (x[0] < y[0] ? -1 : 1)).map(([k, set]) => `- ${k}: ${set.size} name${set.size === 1 ? '' : 's'} (${capped([...set].sort(), 3)})`);
  const where = WORDS.map((w) => [w, nodes.filter((n) => n.path.toLowerCase().includes(w)).map((n) => n.path)]).filter(([, l]) => l.length).map(([w, l]) => `- ${w}: ${capped(l, 3)}`);
  const section = (title, list, none) => [`## ${title}`, '', ...(list.length ? list : [none]), ''];
  out['graph/INDEX.md'] = [
    ...head('Code graph: where to look'),
    'Open `graph/<domain>.md` for one line per file (what it defines, which `AHM.*` calls and events it uses, who uses it). The contract is `INTERFACES.md`; the owners are in `tools/domains.json`.',
    '',
    ...table,
    '',
    ...section('Flags', [...longFiles, ...dups], 'None.'),
    ...section('Cross-domain uses of top-level names (not through `AHM.*`; compare with the contract)', cross, 'None.'),
    ...section('Where to look (by file name)', where, 'None.'),
  ].join('\n');
  const isize = Buffer.byteLength(out['graph/INDEX.md']);
  if (isize > lim.index) problems.push(`graph/INDEX.md is ${isize} bytes, limit ${lim.index}: shorten the flags or the word list in tools/make-graph.js`);
  return { files: out, problems };
}

/** Files of `expected` that differ from `existing`, and files of `existing` that no longer belong. */
function stale(expected, existing) {
  const bad = Object.keys(expected).filter((f) => existing[f] !== expected[f]);
  return [...bad, ...Object.keys(existing).filter((f) => !(f in expected))].sort();
}

function readTree(dir = ROOT) {
  const out = {};
  const walk = (rel) => {
    for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      if (e.isDirectory()) {
        if (e.name !== 'node_modules' && !(rel === '' && TOP_SKIP.has(e.name)) && rel + e.name !== 'app/dist') walk(rel + e.name + '/'); // app/dist is generated (tools/build.js)
      } else if (/\.(js|php)$/.test(e.name)) out[rel + e.name] = fs.readFileSync(path.join(dir, rel, e.name), 'utf8');
    }
  };
  walk('');
  return out;
}

function readGraph() {
  const out = {};
  if (fs.existsSync(GRAPH)) for (const f of fs.readdirSync(GRAPH)) if (f.endsWith('.md')) out['graph/' + f] = fs.readFileSync(path.join(GRAPH, f), 'utf8');
  return out;
}

function main(argv) {
  const r = build(readTree(), cd.ownerOf);
  const old = readGraph();
  if (argv[0] === '--check') {
    const s = stale(r.files, old);
    if (s.length) return console.error('out of date (run node tools/make-graph.js): ' + s.join(', ')), 1;
    if (r.problems.length) return console.error(r.problems.join('\n')), 1;
    return 0;
  }
  fs.mkdirSync(GRAPH, { recursive: true });
  for (const f of Object.keys(r.files)) fs.writeFileSync(path.join(ROOT, f), r.files[f]);
  for (const f of Object.keys(old)) if (!(f in r.files)) fs.rmSync(path.join(ROOT, f));
  console.log('wrote ' + Object.keys(r.files).sort().join(', '));
  if (r.problems.length) return console.error(r.problems.join('\n')), 1;
  return 0;
}
if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { build, stale, parse, LIMITS };
