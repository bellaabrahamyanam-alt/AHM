#!/usr/bin/env bash
# The whole CI in ONE job (DOMAINS.md, "Git workflow"); .github/workflows/ci.yml and .gitlab-ci.yml run only this file.
#  1. pull request: branch/domain check (tools/ci-check-pr.js). A change of documents only stops here (no graph, no tests).
#  2. graph/: in a pull request the job rebuilds it (tools/make-graph.js) and, when it changed, commits it to the pull request branch
#     and stops; the run of that new commit runs the tests. It needs the variable GRAPH_PUSH_TOKEN (DOMAINS.md, owner setup 4).
#     On master the job only checks (make-graph.js --check) and fails when graph/ is stale.
#  3. tests: PHP, data and all JS tests (browser and lint included). Every failing part is reported, not only the first.
set -euo pipefail

# Paths whose change needs tests. Documents (*.md, changes/, tools/prompts/, .claude/) do not.
# A new top-level folder with code or config must be added here.
CODE='^(app|controller|service|config|event|language|styles|data|dev|tests|context|graph)/|^tools/[^/]+$|^\.gitlab/CODEOWNERS$|^\.gitlab-ci\.yml$|^\.github/(workflows/|CODEOWNERS$)|^[^/]+\.(php|json)$'

mr="${CI_MERGE_REQUEST_IID:-}"
if [ -n "$mr" ]; then
  target="origin/${CI_MERGE_REQUEST_TARGET_BRANCH_NAME}"
  git fetch -q origin "$CI_MERGE_REQUEST_TARGET_BRANCH_NAME"
  node tools/ci-check-pr.js "$CI_MERGE_REQUEST_SOURCE_BRANCH_NAME" "$target"
  changed="$(git diff --name-only --no-renames "$target...HEAD")"
elif git rev-parse -q --verify HEAD~1 >/dev/null; then
  changed="$(git diff --name-only --no-renames HEAD~1 HEAD)"
else
  changed='app/'
fi

if ! grep -Eq "$CODE" <<<"$changed"; then
  echo 'documents only: no graph, no tests'
  exit 0
fi

if [ -n "$mr" ]; then
  node tools/make-graph.js
  if [ -n "$(git status --porcelain -- graph)" ]; then
    if [ -z "${GRAPH_PUSH_TOKEN:-}" ]; then
      echo "graph/ is stale and GRAPH_PUSH_TOKEN is not set. Run 'node tools/make-graph.js' and commit graph/, or set the variable (DOMAINS.md, owner setup 4)." >&2
      exit 1
    fi
    git config user.name 'ahm-ci'
    git config user.email 'ahm-ci@users.noreply.gitlab.com'
    git add -A -- graph
    git commit -q -m 'chore: update graph/ (generated by CI)'
    GIT_TERMINAL_PROMPT=0 git push -q "https://ahm-ci:${GRAPH_PUSH_TOKEN}@${CI_SERVER_HOST}/${CI_PROJECT_PATH}.git" "HEAD:refs/heads/${CI_MERGE_REQUEST_SOURCE_BRANCH_NAME}"
    echo "graph/ committed to ${CI_MERGE_REQUEST_SOURCE_BRANCH_NAME}; the pipeline of the new commit runs the tests"
    exit 0
  fi
else
  node tools/make-graph.js --check
fi

apt-get update -qq
apt-get install -y -qq php-cli php-mbstring
npm install -g --no-fund --no-audit eslint@9 playwright
npx playwright install --with-deps chromium
NODE_PATH="$(npm root -g)"
export NODE_PATH

fail=0
run() {
  echo "== $*"
  "$@" || {
    echo "FAILED: $*" >&2
    fail=1
  }
}
run php tests/php/run.php
run php tests/data/run.php
run node tests/js/run.js
exit "$fail"
